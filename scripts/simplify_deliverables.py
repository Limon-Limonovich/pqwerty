"""Краткий отчёт и стандартное оформление Excel без потери кэша формул."""
from pathlib import Path
from zipfile import ZipFile, ZIP_DEFLATED
import xml.etree.ElementTree as ET
from docx import Document
from docx.shared import Pt, Cm

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'Результат'
NS = 'http://schemas.openxmlformats.org/spreadsheetml/2006/main'
Q = lambda s: '{'+NS+'}'+s

def simplify():
    path = OUT / 'Практические_задания.xlsx'
    with ZipFile(path) as z:
        files = {name: z.read(name) for name in z.namelist()}
    # Убираем длинные пояснения с рабочих листов; детали есть в Word.
    strings = ET.fromstring(files['xl/sharedStrings.xml'])
    for item in strings:
        for node in item.iter(Q('t')):
            value = node.text or ''
            if len(value) > 180:
                node.text = 'Пояснения и допущения — в отчёте Word.'
            elif value.startswith('Все задания выполнены в одной книге.'):
                node.text = 'Все задания в одной книге. Входные данные можно менять; формулы пересчитываются.'
    files['xl/sharedStrings.xml'] = ET.tostring(strings, encoding='utf-8', xml_declaration=True)
    root = ET.fromstring(files['xl/styles.xml'])
    # Обычные Calibri 11, без границ/заливок/декоративного выравнивания.
    fonts = root.find(Q('fonts')); fonts.clear(); fonts.set('count','1')
    font = ET.SubElement(fonts,Q('font'))
    for tag,attrs in [('sz',{'val':'11'}),('color',{'theme':'1'}),('name',{'val':'Calibri'}),('family',{'val':'2'}),('scheme',{'val':'minor'})]:
        ET.SubElement(font,Q(tag),attrs)
    fills = root.find(Q('fills')); fills.clear(); fills.set('count','2')
    for pattern in ['none','gray125']:
        ET.SubElement(ET.SubElement(fills,Q('fill')),Q('patternFill'),{'patternType':pattern})
    borders = root.find(Q('borders')); borders.clear(); borders.set('count','1')
    border=ET.SubElement(borders,Q('border'))
    for tag in ['left','right','top','bottom','diagonal']:ET.SubElement(border,Q(tag))
    for collection in ['cellStyleXfs','cellXfs']:
        for xf in root.find(Q(collection)):
            xf.set('fontId','0'); xf.set('fillId','0'); xf.set('borderId','0')
            for attr in list(xf.attrib):
                if attr.startswith('apply') and attr!='applyNumberFormat':del xf.attrib[attr]
            wrap = any(child.tag == Q('alignment') and child.get('wrapText') == '1' for child in xf)
            for child in list(xf):xf.remove(child)
            if wrap:
                ET.SubElement(xf,Q('alignment'),{'wrapText':'1'})
                xf.set('applyAlignment','1')
    dxfs=root.find(Q('dxfs'))
    if dxfs is not None:dxfs.clear();dxfs.set('count','0')
    files['xl/styles.xml']=ET.tostring(root,encoding='utf-8',xml_declaration=True)
    for name,data in list(files.items()):
        if not (name.startswith('xl/worksheets/sheet') and name.endswith('.xml')):continue
        root=ET.fromstring(data)
        for el in root.findall(Q('conditionalFormatting')):root.remove(el)
        for view in root.iter(Q('sheetView')):view.set('showGridLines','1')
        # Длинные пояснения остаются в Word; в книге только краткие примечания.
        for row in root.iter(Q('row')):
            if row.get('ht') not in ('58','48'):
                row.attrib.pop('ht',None);row.attrib.pop('customHeight',None)
        # Заголовки остаются читаемыми без заливки и полужирного шрифта.
        files[name]=ET.tostring(root,encoding='utf-8',xml_declaration=True)
    with ZipFile(path,'w',ZIP_DEFLATED) as z:
        for name,data in files.items():z.writestr(name,data)

    doc=Document()
    sec=doc.sections[0];sec.top_margin=sec.bottom_margin=Cm(1.7)
    sec.left_margin=sec.right_margin=Cm(2)
    normal=doc.styles['Normal'];normal.font.name='Calibri';normal.font.size=Pt(11)
    normal.paragraph_format.space_after=Pt(4)
    def p(s):doc.add_paragraph(s)
    def h(s):doc.add_heading(s,2)
    def table(headers,rows):
        t=doc.add_table(rows=1,cols=len(headers));t.style='Table Grid'
        for c,v in zip(t.rows[0].cells,headers):c.text=v
        for row in rows:
            for c,v in zip(t.add_row().cells,row):c.text=str(v)
    doc.add_heading('Отчёт: электронные таблицы',0)
    p('Выполнены задания по 48 скриншотам. Приложение: «Практические_задания.xlsx» — 18 листов, 206 формул, 13 диаграмм. Все пять итоговых вариантов включены в одну книгу.')
    h('1. Отчёт «ТекстильПром»')
    table(['Продукция','План / факт, шт.','Выполнение','Прибыль, ₽'],[
        ['Платья','500 / 470','94%','470 000'],['Футболки','300 / 300','100%','75 000'],
        ['Джинсы','400 / 460','115%','414 000'],['Юбки','470 / 450','95,74%','135 000']])
    p('Итого: план 1 670 шт., факт 1 680 шт., выполнение 100,60%, прибыль 1 094 000 ₽. Наибольшую прибыль дают платья. План не выполнен по платьям и юбкам.')
    p('Формулы: выполнение = факт / план × 100; прибыль на единицу = цена − себестоимость; общая прибыль = прибыль на единицу × факт. Круговая диаграмма построена по общей прибыли.')
    h('2. Задачи по функциям')
    table(['№','Расчёт','Результат'],[
        ['1','СУММ и СРЗНАЧ для 10, 20, …, 100','550; 55'],
        ['2','СРЗНАЧЕСЛИ, исключая нули','40'],
        ['3','ЕСЛИ: покупка 6 000 ₽, скидка 10%','К оплате 5 400 ₽'],
        ['4','ЕСЛИ + И: возраст 18, подписка «Да»','Доступ разрешён'],
        ['5','РАБДЕНЬ: 01.10.2024 + 10 рабочих дней','15.10.2024, вторник'],
        ['6','РАБДЕНЬ и ДЕНЬНЕД: проверка пятницы','15.10.2024 — не пятница'],
        ['7','СРЗНАЧ, ИНДЕКС, ПОИСКПОЗ, СЧЁТЕСЛИ','Среднее 176,25 тыс. ₽; максимум — декабрь, 300 тыс. ₽; выше среднего — 6 месяцев']])
    h('3. Самостоятельные задачи')
    p('1. Стоимость: ОКРУГЛ(3,5 × 1200 × 250 × 1,2; 2) = 1 260 000 ₽ с НДС; без НДС — 1 050 000 ₽.')
    p('2. Качество: ЕСЛИ(И(A2>=50;ИЛИ(B2<=5;C2="Массмаркет"));"Годна";"Брак"). Для примеров 55 / 4 / Премиум — «Годна»; 48 / 3 / Массмаркет — «Брак».')
    p('3. Срок: РАБДЕНЬ.МЕЖД(A2;C2;1;$B$2:$B$3). От 10.06.2025 за 15 рабочих дней, исключая 12 и 13 июня: 03.07.2025.')
    p('4. Пять учебных партий: средний брак 2,5759%; наибольшее стоимостное отклонение — партия 1, +20 000 ₽; выборочное стандартное отклонение себестоимости — 15,8114 ₽/м.')
    h('4. Итоговые варианты')
    table(['Вариант','Основной результат'],[
        ['1. Рабочее время','39 ч; начисленная зарплата 14 880 ₽. Учтена смена через полночь.'],
        ['2. Склад','Остаток 810 м; пополнить 3 позиции, всего на 90 м.'],
        ['3. Производство','Годный выпуск 1 652 шт.; выполнение 98,92%; брак 1,67%.'],
        ['4. Доставка','830 км; топливо 88,1 л; стоимость 15 686,50 ₽.'],
        ['5. Показатели цеха','Затраты 813 000 ₽; выручка 1 874 900 ₽; прибыль 1 061 900 ₽; рентабельность затрат 130,62%.']])
    p('В каждом варианте использовано не менее трёх разных функций и две диаграммы разных типов. Формулы пересчитываются при изменении исходных данных. В варианте 5 показатели связаны с листами производства и цен.')
    h('5. Короткие ответы на вопросы')
    for s in [
        'Информация — сведения об объектах и процессах. Формы: текстовая, числовая, графическая, звуковая и видео. В работе использована табличная форма.',
        'Таблица удобнее сплошного текста для поиска, сравнения и вычислений. Чтобы преобразовать текст в таблицу, выделяют объекты (строки) и свойства (столбцы).',
        'Структура: книга → лист → строки и столбцы → ячейки и диапазоны. В ячейки вводят текст, числа, даты, время, логические значения и формулы.',
        'Создать таблицу — задать структуру, ввести данные и формулы. В отличие от таблицы в тексте она автоматически пересчитывает результаты.',
        'Формула начинается с =. Операторы: +, −, *, /, ^. Копирование: маркер заполнения или Ctrl+C/Ctrl+V. Относительная ссылка меняется, абсолютная ($L$2) фиксируется.',
        'Числовой формат округляет только отображение; ОКРУГЛ — результат. Для юбок точное выполнение плана 95,74468…%, на листе отчёта показано 96.',
        'Категории функций: математические, статистические, логические, текстовые, дата/время, ссылки и массивы, базы данных. Чаще нужны СУММ, СРЗНАЧ и ЕСЛИ для итогов и проверок.',
        'Типичные ошибки: неверные ссылки, текст вместо числа, пропущенные скобки, деление на ноль. Нужно проверять диапазоны, типы данных и граничные случаи; ЕСЛИОШИБКА не заменяет проверку исходных данных.',
        'Применение: личный бюджет, сравнение цен, зарплата, склад, сметы, сроки заказов и логистика. Автоматизация экономит время и сокращает повторный ввод.',
        'Освоены ввод и организация данных, формулы, функции, копирование, форматирование чисел, диаграммы и анализ результатов.',
        'Структура зависит от задачи, пользователей и объёма данных. Принципы: одна строка на объект, понятные единицы, разделение ввода и расчётов. Учёт фиксирует события; анализ выявляет отклонения и помогает принимать решения.'
    ]:p('• '+s)
    h('Примечания и вывод')
    p('Данные, отсутствующие в условии, выбраны как учебные. В задаче качества исправлены адреса ячеек; прочность обязательна для обоих сегментов. В РАБДЕНЬ.МЕЖД добавлен пропущенный аргумент выходных. В обеих задачах 5–6 используются рабочие дни. Календарь заказа: пятидневка РФ, 12 и 13 июня 2025 исключены.')
    p('«Рентабельность» пяти партий по формуле сценария — стоимостное отклонение, не процент прибыли. В варианте 5 рентабельность = прибыль / затраты. Прибыль рассчитана при продаже всего годного выпуска.')
    p('По просьбе пользователя Excel оформлен без декоративных стилей и цветовых выделений. Пятница и минимальные запасы обозначены текстом; цветовая подсветка из исходного сценария снята. Форматы чисел, дат и времени сохранены.')
    p('Вывод: общий план цеха перевыполнен, но отдельные позиции отстают. Учёт брака снижает годный выпуск и прибыль, поэтому оценивать нужно одновременно объём, качество и затраты. Файлы проверены программно; настольные Excel и Word не запускались.')
    doc.save(OUT/'Отчёт_по_уроку.docx')

if __name__=='__main__':simplify()
